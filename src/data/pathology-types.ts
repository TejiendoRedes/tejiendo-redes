/**
 * Obtener todos los tipos de patología
 */
export function getPathologyTypes(): PathologyType[] {
    return PATHOLOGY_TYPES;
}

/**
 * Buscar tipos de patología por término de búsqueda
 */
export function searchPathologyTypes(query: string): PathologyType[] {
    if (!query.trim()) return PATHOLOGY_TYPES;

    const lowerQuery = query.toLowerCase();
    return PATHOLOGY_TYPES.filter(type =>
        type.nombre.toLowerCase().includes(lowerQuery) ||
        type.id.toLowerCase().includes(lowerQuery)
    );
}

/**
 * Obtener nombre de tipo de patología por ID
 */
export function getPathologyTypeName(id: string): string {
    const type = PATHOLOGY_TYPES.find(t => t.id === id);
    return type ? type.nombre : id;
}
